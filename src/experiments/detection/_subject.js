// Immediately after estimation, because they are the same question asked twice:
// estimation reads a parameter off the data, detection decides between two
// hypotheses about it. A course that separates them makes the likelihood ratio
// look like a new object instead of the likelihood already met next door.
// Both words are in the title because the last experiment of the module proves
// they name one thing. For two Gaussian classes of equal covariance the exact
// log-likelihood ratio is affine, so the posterior is a sigmoid of a linear
// form — which is precisely the model logistic regression postulates. A
// classifier is a detector whose ratio was estimated rather than derived, and
// the module is ordered as a ladder of what is known: both densities, then the
// signal, then the signal up to a parameter, then nothing but examples.
export default { title: 'Detection and classification', order: 3 };
